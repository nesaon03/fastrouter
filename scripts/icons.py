#!/usr/bin/env python3
"""Keep the dashboard's Material Symbols subset in sync with the icons it uses.

  python3 scripts/icons.py           # list used icons, rebuild the subset font, verify, write the manifest
  python3 scripts/icons.py --check   # only check used icons against the manifest (what the Go test does)

"Used" = every string literal in static/*.js|*.html (and text inside class="ms" elements)
that is a real Material Symbols name (internal/dashboard/testdata/material-symbols-all.txt).
The font is downloaded from Google Fonts as woff2 (shipped) and woff (same subset, read with
fontTools to confirm every name has a ligature glyph). The manifest records the verified names
and the woff2's sha256, so the Go test fails if the font or the code drift apart.
"""
import glob, hashlib, io, os, re, sys, urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "internal", "dashboard")
STATIC = os.path.join(ROOT, "static")
FONT = os.path.join(STATIC, "fonts", "material-symbols.woff2")
ALL = os.path.join(ROOT, "testdata", "material-symbols-all.txt")
MANIFEST = os.path.join(ROOT, "testdata", "material-symbols-subset.txt")
CSS = "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0..1,0&icon_names={}&display=block"
UA_WOFF2 = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"
UA_WOFF = "Mozilla/5.0 (Windows NT 6.1) AppleWebKit/534.30 (KHTML, like Gecko) Safari/534.30"


def used_icons():
    valid = set(open(ALL).read().split())
    found = set()
    for f in sorted(glob.glob(os.path.join(STATIC, "*.js")) + glob.glob(os.path.join(STATIC, "*.html"))):
        s = open(f, encoding="utf-8").read()
        found |= set(re.findall(r"[\"'`]([a-z0-9_]+)[\"'`]", s))
        found |= set(re.findall(r"class=\"ms[^\"]*\"[^>]*>\s*([a-z0-9_]+)\s*<", s))
    return sorted(found & valid)


def fetch(url, ua=None):
    req = urllib.request.Request(url, headers={"User-Agent": ua} if ua else {})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def font_url(names, ua):
    css = fetch(CSS.format(",".join(names)), ua).decode()
    m = re.search(r"url\((https://[^)]+)\)", css)
    if not m:
        sys.exit("no font URL in Google Fonts CSS")
    return m.group(1)


def ligatures(data):
    from fontTools.ttLib import TTFont
    f = TTFont(io.BytesIO(data))
    rev = {g: chr(c) for c, g in f.getBestCmap().items()}
    out = set()
    for lk in f["GSUB"].table.LookupList.Lookup:
        for st in lk.SubTable:
            if lk.LookupType == 7:
                st = st.ExtSubTable
            if getattr(st, "LookupType", lk.LookupType) != 4:
                continue
            for first, ligs in st.ligatures.items():
                for l in ligs:
                    out.add("".join(rev.get(g, "?") for g in [first] + list(l.Component)))
    return out


def read_manifest():
    if not os.path.exists(MANIFEST):
        return "", set()
    sha, names = "", set()
    for line in open(MANIFEST):
        line = line.strip()
        if line.startswith("# sha256 "):
            sha = line.split()[2]
        elif line and not line.startswith("#"):
            names.add(line)
    return sha, names


def check():
    sha, names = read_manifest()
    real = hashlib.sha256(open(FONT, "rb").read()).hexdigest()
    bad = []
    if sha != real:
        bad.append("font file changed without regenerating the manifest (run scripts/icons.py)")
    missing = [n for n in used_icons() if n not in names]
    if missing:
        bad.append("icons used but missing from the font subset: " + ", ".join(missing))
    for b in bad:
        print("icons:", b)
    return not bad


def main():
    if "--check" in sys.argv:
        sys.exit(0 if check() else 1)
    names = used_icons()
    woff2 = fetch(font_url(names, UA_WOFF2))
    woff = fetch(font_url(names, UA_WOFF))
    glyphs = ligatures(woff)
    missing = [n for n in names if n not in glyphs]
    if missing:
        sys.exit("Google's subset lacks: " + ", ".join(missing))
    if woff2[:4] != b"wOF2":
        sys.exit("downloaded font is not woff2")
    open(FONT, "wb").write(woff2)
    with open(MANIFEST, "w") as m:
        m.write("# Material Symbols in static/fonts/material-symbols.woff2 (generated by scripts/icons.py; do not edit)\n")
        m.write("# sha256 %s\n" % hashlib.sha256(woff2).hexdigest())
        m.write("\n".join(names) + "\n")
    print("%d icons, %d bytes, every ligature verified" % (len(names), len(woff2)))


if __name__ == "__main__":
    main()
