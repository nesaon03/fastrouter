#!/usr/bin/env python3
"""Generate internal/catalog/registry_gen.go from a JSON dump of 9Router's
provider registry (MIT, decolua/9router). Usage: gen_catalog.py reg.json out.go"""
import json, sys

CORE = {"deepseek", "openrouter", "opencode-go", "xiaomi-tokenplan", "openai", "gemini", "nvidia", "xai", "anthropic",
        "codex", "glm", "antigravity", "cursor", "opencode"}
CORE_KEYS = CORE | {"ds", "ocg", "xmtp", "claude", "cx", "ag", "cu", "oc"}

reg = json.load(open(sys.argv[1]))
reg.sort(key=lambda x: x["id"])

def q(s):
    return json.dumps(s or "")

def routable(x):
    if x["id"] in CORE or x.get("noAuth") or x.get("hidden"):
        return None
    if x["category"] not in ("apikey", "freeTier") or x.get("authType") not in (None, "apikey"):
        return None
    kinds = x.get("serviceKinds")
    if kinds and "llm" not in kinds:
        return None
    base, fmt = x.get("base") or "", x.get("format")
    if not base.startswith("https://") or "{" in base:
        return None
    if fmt in (None, "openai") and base.endswith("/chat/completions"):
        return ("ChatURL", base)
    if fmt == "claude" and base.endswith("/messages"):
        return ("MessagesURL", base)
    if fmt == "openai-responses" and base.endswith("/responses"):
        return ("ResponsesURL", base)
    return None

used = set(CORE_KEYS)
extras = []
for x in reg:
    r = routable(x)
    if not r or x["id"] in used:
        continue
    used.add(x["id"])
    alias = x.get("alias")
    aliases = []
    if alias and alias != x["id"] and alias not in used:
        aliases.append(alias)
        used.add(alias)
    extras.append((x, r, aliases))

out = ["// Code generated by scripts/gen_catalog.py from 9Router's provider registry (MIT, decolua/9router). DO NOT EDIT.", "",
       "package catalog", "", "// extras are API-key providers beyond the hand-tuned core list. Their prefixes never",
       "// shadow a custom endpoint (see Reserved).", "var extras = []Provider{"]
for x, (field, url), aliases in extras:
    up = {m["id"]: m["up"] for m in x["models"] if m.get("up") and m["up"] != m["id"]}
    line = f'\t{{ID: {q(x["id"])}, {field}: {q(url)}, Extra: true'
    if aliases:
        line += ", Aliases: []string{" + ", ".join(q(a) for a in aliases) + "}"
    if up:
        line += ", Upstream: map[string]string{" + ", ".join(f"{q(k)}: {q(v)}" for k, v in sorted(up.items())) + "}"
    out.append(line + "},")
out += ["}", "", "// display holds names, colours and key pages for every 9Router provider, routable or not.",
        "var display = map[string]Display{"]
for x in reg:
    if x.get("hidden"):
        continue
    out.append(f'\t{q(x["id"])}: {{Name: {q(x.get("name") or x["id"])}, Color: {q(x.get("color"))}, Category: {q(x["category"])}, KeyURL: {q(x.get("keyUrl"))}}},')
out += ["}", "", "// models are the LLM ids 9Router lists per provider, for the model picker.", "var models = map[string][]Model{"]
for x in reg:
    ms = [m for m in x["models"] if m.get("id")]
    if not ms:
        continue
    out.append(f'\t{q(x["id"])}: {{' + ", ".join(f'{{{q(m["id"])}, {q(m.get("name") or m["id"])}}}' for m in ms) + "},")
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(len(extras), "extra providers;", sum(1 for x in reg if not x.get("hidden")), "display entries", file=sys.stderr)
